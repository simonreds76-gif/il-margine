// Deterministic web exports of the supplied artwork. No redraw or upscaling.
import fs from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';
import pngToIco from 'png-to-ico';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'data/brand/newlogoilmargine-20260913.png');
const out = path.join(root, 'public/brand/20260913');
await fs.mkdir(out, { recursive: true });
const metadata = await sharp(source).metadata();
if (metadata.width !== 1942 || metadata.height !== 809) throw new Error('Unexpected source artwork dimensions');
const background = '#090f12';
const emblem = await sharp(source).extract({ left: 244, top: 70, width: 520, height: 640 }).png().toBuffer();
const full = await sharp(source).extract({ left: 230, top: 60, width: 1515, height: 650 }).png().toBuffer();
const wordmark = await sharp(source).extract({ left: 785, top: 279, width: 955, height: 245 }).png().toBuffer();
const compact = await sharp({ create: { width: 700, height: 168, channels: 3, background } })
  .composite([
    { input: await sharp(emblem).resize({ height: 156 }).toBuffer(), left: 4, top: 6 },
    { input: await sharp(wordmark).resize({ width: 516 }).toBuffer(), left: 174, top: 18 },
  ]).png().toBuffer();
await sharp(compact).webp({ quality: 90, effort: 6 }).toFile(path.join(out, 'logo-compact.webp'));
await sharp(full).resize({ width: 900 }).webp({ quality: 90, effort: 6 }).toFile(path.join(out, 'logo-full.webp'));
await sharp(full).resize({ width: 900 }).png({ palette: true, colours: 192 }).toFile(path.join(out, 'logo.png'));
const square = await sharp(emblem).resize(512, 512, { fit: 'contain', background }).png().toBuffer();
await sharp(square).webp({ quality: 90 }).toFile(path.join(out, 'icon.webp'));
for (const size of [16, 32, 48, 128, 180, 192, 256, 512]) {
  await sharp(square).resize(size, size).png({ palette: true, colours: 128 }).toFile(path.join(out, `icon-${size}.png`));
}
const ico = await pngToIco([16, 32, 48].map(size => path.join(out, `icon-${size}.png`)));
await fs.writeFile(path.join(root, 'src/app/favicon.ico'), ico);
await fs.writeFile(path.join(out, 'favicon.ico'), ico);
const social = await sharp({ create: { width: 1200, height: 630, channels: 3, background } })
  .composite([{ input: await sharp(full).resize({ width: 1080 }).toBuffer(), left: 60, top: 83 }])
  .png({ palette: true, colours: 192 }).toBuffer();
await fs.writeFile(path.join(out, 'social.png'), social);
// Compatibility URLs for existing bookmarks and already-indexed publisher images.
await fs.copyFile(path.join(out, 'logo.png'), path.join(root, 'public/logo.png'));
for (const size of [32, 128, 256]) {
  await fs.copyFile(path.join(out, `icon-${size}.png`), path.join(root, `public/favicon${size===32?'':'-'+size}.png`));
}
for (const name of ['og.png', 'og-social-20260629.png']) await fs.writeFile(path.join(root, 'public', name), social);
// Small embedded asset: OG/Telegram rendering needs no extra remote fetch.
const cardLogo = await sharp(compact).resize({ width: 420 }).png({ palette: true, colours: 96 }).toBuffer();
await fs.writeFile(path.join(root, 'src/lib/site-brand-image.ts'),
  '// Generated by scripts/build-site-brand-assets.mjs; do not hand edit.\n'+
  `export const SITE_BRAND_IMAGE = "data:image/png;base64,${cardLogo.toString('base64')}";\n`);
const files = await Promise.all((await fs.readdir(out)).map(async name => ({ name, bytes: (await fs.stat(path.join(out,name))).size })));
await fs.writeFile(path.join(root,'data/brand/logo-rollout-20260913.json'), JSON.stringify({ source: path.basename(source), width:metadata.width,height:metadata.height, opaque:true,files },null,2)+'\n');
console.log(JSON.stringify(files,null,2));
