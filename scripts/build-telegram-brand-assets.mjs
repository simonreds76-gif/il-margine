// Regenerate only when official artwork changes; never at request time.
import fs from 'node:fs/promises';
import sharp from 'sharp';
const brands = { betway: 'public/bookmakers/betway-official.svg', williamhill: 'public/bookmakers/williamhill-official.svg' };
const assets = {};
for (const [key, file] of Object.entries(brands)) {
  const png = await sharp(await fs.readFile(file), { density: 192 }).trim()
    .resize({ width: 620, height: 200, fit: 'inside' }).png().toBuffer();
  assets[key] = `data:image/png;base64,${png.toString('base64')}`;
}
await fs.writeFile('src/lib/telegram-brand-assets.ts',
  '// Generated by scripts/build-telegram-brand-assets.mjs. Official artwork embedded to avoid network/cache failures.\n' +
  'export const TELEGRAM_BRAND_ASSETS: Record<string, string> = ' + JSON.stringify(assets, null, 2) + ';\n');
console.log('Embedded Telegram logos:', Object.keys(assets).join(', '));
