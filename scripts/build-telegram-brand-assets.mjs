// Regenerate only when official artwork changes; never at request time.
import fs from 'node:fs/promises';
import sharp from 'sharp';
import ts from 'typescript';
const identityModule = { exports: {} };
const code = ts.transpileModule(await fs.readFile('src/lib/bookmaker-logos.ts', 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS },
}).outputText;
new Function('exports', code)(identityModule.exports);
const { BOOKMAKER_LOGO_KEYS, resolveBookmakerLogo } = identityModule.exports;
const official = { betway: 'public/bookmakers/betway-official.svg', williamhill: 'public/bookmakers/williamhill-official.svg',
  paddypower: 'public/bookmakers/paddypower-official.png', betfair: 'public/bookmakers/betfair-official.png', skybet: 'public/bookmakers/skybet-official.png' };
const assets = {};
const aspects = {};
for (const key of BOOKMAKER_LOGO_KEYS) {
  const file = official[key] || `public${decodeURIComponent(resolveBookmakerLogo(key).paths[0])}`;
  const png = await sharp(await fs.readFile(file), { density: 192 }).trim()
    .resize({ width: 480, height: 144, fit: 'inside' })
    .png({ palette: true, colours: 128, dither: 0, effort: 7 }).toBuffer();
  const metadata = await sharp(png).metadata();
  aspects[key] = metadata.width / metadata.height;
  assets[key] = `data:image/png;base64,${png.toString('base64')}`;
}
const generated =
  '// Generated by scripts/build-telegram-brand-assets.mjs. Bundled artwork avoids request-time network/cache failures.\n' +
  'export const TELEGRAM_BRAND_ASSETS: Record<string, string> = ' + JSON.stringify(assets, null, 2) + ';\n' +
  'export const TELEGRAM_BRAND_ASPECTS: Record<string, number> = ' + JSON.stringify(aspects, null, 2) + ';\n';
if (Buffer.byteLength(generated) > 150_000) throw new Error('Telegram logo bundle exceeds its 150 KB budget');
await fs.writeFile('src/lib/telegram-brand-assets.ts', generated);
console.log('Embedded Telegram logos:', Object.keys(assets).join(', '));
